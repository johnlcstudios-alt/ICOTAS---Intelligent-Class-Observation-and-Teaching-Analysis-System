$tokenHint = '';

if (($token) && isset($token) && $token !== '' && $token !== null && $token !== '0') {
    // When we have a token, render the access card + scanner JS from the controller's shared data.
    $qrcodeSrc = QRScannerService::imageSrc((string) $token);
    $tokenHint = 'Use the scanner in an incognito window, or paste the link in a private browser.';
    $showCheckout = true;
}

$showCheckout = !empty($showCheckout);
$tokenUrlEncoded = rawurlencode((string) $token);
?>
<div class="page-tools">
    <a class="btn btn--ghost" href="<?= e(url('/faculty/access')) ?>"><?= icon('list', 16) ?> Courses</a>
    <?php if ($showCheckout): ?>
        <a class="btn btn--ghost" href="<?= e(url('/faculty/qr/scanner')) ?>"><?= icon('scan', 16) ?> Scanner</a>
    <?php endif; ?>
</div>

<div class="faculty-access">
    <div class="faculty-access__intro">
        <h1><?= e($pageTitle) ?></h1>
        <p class="muted small"><?= e($pageSubtitle) ?></p>
    </div>

    <?php if ($messages): ?>
        <div class="faculty-access__messages">
            <?php foreach ($messages as $msg): ?>
                <div class="alert alert--<?= e($msg['type'] === 'error' ? 'danger' : ($msg['type'] === 'success' ? 'success' : 'info')) ?>">
                    <span class="alert__icon"><?= icon($msg['type'] === 'error' ? 'alert-circle' : ($msg['type'] === 'success' ? 'check-circle' : 'info'), 18) ?></span>
                    <div class="alert__body"><?= e($msg['text']) ?></div>
                </div>
            <?php endforeach; ?>
        </div>
    <?php endif; ?>

    <?php if ($showCheckout): ?>
        <div class="faculty-access__checkout">
            <div class="checkout-card">
                <div class="checkout-card__header">
                    <div class="checkout-card__title">
                        Verify observation
