                    </div>
                </div>

                <div class="checkout-card__body">
                    <div class="checkout-card__qrcode">
                        <?php if ($qrcodeSrc): ?>
                            <img src="<?= e($qrcodeSrc) ?>" alt="QR code for access" class="qrcode-image">
                        <?php else: ?>
                            <div class="qrcode-placeholder">
                                <?= icon('qrcode', 32) ?>
                                <span class="small muted">QR code will be generated by your browser from the link below.</span>
