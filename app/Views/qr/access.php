                    <li>The QR code encodes a one-time access link.</li>
                    <li>Scan the code in a private window; the scanner reads the link, verifies the token, and records the observation.</li>
                    <li>After verification, ICOTAS redirects back and updates the session.</li>
                </ol>
            </div>
        </div>
    <?php endif; ?>
