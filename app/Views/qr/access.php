                            <input id="token-url" class="input input--mono" type="text" value="<?= e(url('/faculty/qr/' . $tokenUrlEncoded . '/image')) ?>" readonly onclick="this.select()">
                            <button type="button" class="btn btn--ghost btn--sm" onclick="(function(input){var t=document.getElementById('token-url');if(t){try{navigator.clipboard.writeText(t.value)}catch(_){}}})(this)">Copy</button>
                        </div>
                    </div>

                    <form class="checkout-card__form" method="post" action="<?= e(url('/faculty/qr/' . $tokenUrlEncoded . '/verify')) ?>">
                        <?= csrf_field() ?>
                        <div class="field field--full">
                            <label for="token">Token <span class="required">*</span></label>
                            <input id="token" class="input input--mono" type="text" name="token" value="<?= e($token) ?>" autocomplete="off" required>
                            <?php if ($tokenHint): ?>
                                <p class="muted small"><?= e($tokenHint) ?></p>
                            <?php endif; ?>
                        </div>
                        <div class="form-actions">
                            <button type="submit" class="btn btn--primary">Verify</button>
                            <a class="btn btn--ghost" href="<?= e(url('/faculty/qr/scanner')) ?>">Cancel</a>
