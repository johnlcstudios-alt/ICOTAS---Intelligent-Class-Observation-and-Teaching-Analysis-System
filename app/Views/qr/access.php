                <div class="checkout-card__footer">
                    <p class="small muted">
                        Use the scanner in a private window, or paste the link in an incognito browser.
                    </p>
                </div>
            </div>

            <!-- Boundary script: the scanner calls this after POSTing the token to /qr/verify. -->
            <script>
            (function () {
                'use strict';
                window.addEventListener('message', function (event) {
                    if (event.source !== window) {
                        return;
                    }
                    var data = event.data;
                    if (!data || typeof data !== 'object') {
                        return;
                    }
                    // Sanity check: only accept messages that look like our boundary.
                    if (!data.token) {
                        return;
                    }
                    var target = document.getElementById('token');
                    if (!target) {
                        return;
                    }
                    if (typeof data.token === 'string') {
                        target.value = data.token;
                    } else if (data.token && typeof data.token === 'object') {
                        try {
                            target.value = data.token.toString();
                        } catch (_) {
                            // ignore
                        }
                    }
                    if (target.value) {
                        // Trigger the hidden form; the form posts to /faculty/qr/{token}/verify.
                        var form = document.querySelector('form.checkout-card__form');
                        if (form) {
                            form.submit();
                        }
                    }
                });
            })();
            </script>
        </div>
    <?php else: ?>
        <div class="faculty-access__list">
